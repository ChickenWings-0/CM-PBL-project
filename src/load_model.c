/*
 * load_model.c - synthetic Delhi household load curve (summer day).
 *
 *   P(t) = B + sum over 3 bumps of  A * exp( -(t - mu)^2 / (2 sigma^2) )
 *
 * Each bump is a bell (Gaussian) curve:
 *   morning peak  (water pump, kettle, iron)       A=1.0 kW at 08:00, sigma 1.0 h
 *   afternoon AC  (hottest hours)                  A=0.8 kW at 15:00, sigma 2.5 h
 *   evening peak  (AC + lights + TV + cooking)     A=3.0 kW at 20:30, sigma 1.5 h
 *
 * Why bell curves and not sine waves? For a sum of sine waves over a full
 * 24 h period the trapezoidal rule is almost exact, which would make the
 * comparison of integration methods misleading (see docs/PLAN.md 2.1).
 */
#include <stdio.h>
#include <math.h>
#include "load_model.h"

#define BASE_LOAD 0.5                   /* kW, always on */
#define N_BUMPS 3

static const double AMP[N_BUMPS]   = {1.0, 0.8, 3.0};    /* height of bump, kW */
static const double MU[N_BUMPS]    = {8.0, 15.0, 20.5};  /* centre, hours      */
static const double SIGMA[N_BUMPS] = {1.0, 2.5, 1.5};    /* width, hours       */

static const double PI = 3.14159265358979323846;

double model_power(double t)
{
    double p = BASE_LOAD;
    int k;
    for (k = 0; k < N_BUMPS; k++) {
        double z = (t - MU[k]) / SIGMA[k];
        p += AMP[k] * exp(-0.5 * z * z);
    }
    return p;
}

/*
 * Exact integral. For one bump:
 *   integral of A exp(-(t-mu)^2/(2 s^2)) dt from a to b
 *     = A * s * sqrt(pi/2) * [ erf((b-mu)/(s sqrt2)) - erf((a-mu)/(s sqrt2)) ]
 * erf() is the "error function" from math.h (C99).
 */
double model_energy(double a, double b)
{
    double e = BASE_LOAD * (b - a);
    int k;
    for (k = 0; k < N_BUMPS; k++) {
        double s2 = SIGMA[k] * sqrt(2.0);
        e += AMP[k] * SIGMA[k] * sqrt(PI / 2.0)
             * (erf((b - MU[k]) / s2) - erf((a - MU[k]) / s2));
    }
    return e;
}

int generate_synthetic_csv(const char *path)
{
    /* Hours whose readings are "lost" (see PLAN.md 2.1 for why these). */
    static const int missing_hours[] = {4, 9, 13, 14, 19};
    const int n_missing = 5;
    FILE *fp = fopen(path, "w");
    int h, j;

    if (fp == NULL) {
        printf("  ERROR: cannot write '%s'\n", path);
        return 0;
    }
    fprintf(fp, "# Synthetic Delhi household, summer day (generated by load_model.c)\n");
    fprintf(fp, "# P(t) = 0.5 + 1.0 g(8,1.0) + 0.8 g(15,2.5) + 3.0 g(20.5,1.5)  [kW]\n");
    fprintf(fp, "# Hours 4, 9, 13, 14, 19 removed on purpose (NA) to simulate lost readings\n");
    fprintf(fp, "time_hours,power_kW\n");
    for (h = 0; h <= 24; h++) {
        int is_missing = 0;
        for (j = 0; j < n_missing; j++)
            if (missing_hours[j] == h) is_missing = 1;
        if (is_missing)
            fprintf(fp, "%d,NA\n", h);
        else
            fprintf(fp, "%d,%.4f\n", h, model_power(h));   /* 4 decimals = 0.1 W */
    }
    fclose(fp);
    return 1;
}
